    // Elemen <a> yang diklik (pakai closest untuk aman kalau ikon di dalamnya diklik)
    const a = e.target.closest('a.whatsapp-btn');
    if (!a) return;

    const url = a.getAttribute('href');
    const label = a.dataset.gtmLabel || a.textContent.trim();
